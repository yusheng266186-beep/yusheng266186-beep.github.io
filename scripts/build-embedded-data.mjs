import { readFile, writeFile,rename } from "node:fs/promises";
import path from "node:path";
import {buildSiteSnapshot} from './site-snapshot.mjs';
import Site from '../assets/site-data.js';
import {writeJson} from './forecast-study-io.mjs';

const root = process.cwd();
const files = {...Object.fromEntries(Object.entries(Site.files).map(([key,file]) => [key,'data/'+file])),
  market: 'data/market-snapshot.json', health: 'data/pipeline-health.json'};

const bytes = {}, payload = {};
await Promise.all(Object.entries(files).map(async ([key, relativePath]) => {
  try {
    const raw = await readFile(path.resolve(root, relativePath));
    payload[key] = JSON.parse(raw);
    bytes[key] = raw;
  } catch {
    payload[key] = null;
  }
}));
const ordered = Object.fromEntries(Object.keys(files).map(key => [key,payload[key]]));
const snapshot = buildSiteSnapshot(ordered, bytes);

if (!process.argv.includes('--index-only')) {
  const output = '/* Generated by scripts/build-embedded-data.mjs for offline use. */\nwindow.__AURUM_DATA__ = '
    + JSON.stringify(ordered).replace(/</g, '\\u003c') + ';\n';
  await writeFile(path.resolve(root, 'data/embedded-data.js.tmp'), output);
  await rename(path.resolve(root, 'data/embedded-data.js.tmp'), path.resolve(root, 'data/embedded-data.js'));
  const bundle = {schema: 1, generatedAt: payload.health?.generatedAt || new Date().toISOString(), market: payload.market,
    history: payload.history, news: payload.news, research: payload.research, ledger: payload.ledger, health: payload.health,
    publication: payload.publication, analysisDesk: payload.analysisDesk};
  await writeJson(path.resolve(root, 'data/research-bundle.json'), bundle);
}
await writeJson(path.resolve(root, 'data/site-snapshot.json'), snapshot);
console.log(JSON.stringify({embedded: 'offline and previous releases', indexBytes: Buffer.byteLength(JSON.stringify(snapshot)), resources: Object.keys(snapshot.resources)}));

